class S:  # 도형 모음 (좌표계 200×200)
    def __init__(s): s.o = []
    def poly(s, pts, c, op=1):
        s.o.append(f'<polygon points="{" ".join(f"{x:.1f},{y:.1f}" for x, y in pts)}" fill="{c}" stroke="{c}" stroke-width="1.4" stroke-linejoin="round"{f" opacity={chr(34)}{op}{chr(34)}" if op < 1 else ""}/>')
    def raw(s, t): s.o.append(t)



    mir = lambda p: [(200 - x, y) for x, y in p]
    def sym(p, cl, cr): s.poly(T(p), cl); s.poly(T(mir(p)), cr)
    sym([(46, 70), (70, 58), (76, 80)], D, X); sym([(46, 70), (76, 80), (54, 86)], X, X); sym([(54, 70), (68, 64), (70, 78)], SN, SND)
    sym([(70, 58), (100, 52), (100, 84)], L, M); sym([(70, 58), (100, 84), (66, 90)], L, M); sym([(70, 58), (66, 90), (54, 86)], M, D)
    sym([(54, 86), (66, 90), (46, 112)], M, D); sym([(66, 90), (100, 84), (78, 108)], L, M); sym([(100, 84), (100, 104), (78, 108)], L, M)
    sym([(46, 112), (66, 90), (78, 108)], L, M); sym([(46, 112), (78, 108), (52, 138)], M, D)
    sym([(52, 138), (78, 108), (80, 148)], M, D); sym([(52, 138), (80, 148), (66, 156)], D, X)
    sym([(66, 156), (80, 148), (100, 160)], M, D); sym([(80, 148), (100, 150), (100, 160)], M, D)
    sym([(100, 104), (78, 108), (74, 124)], SN, SND); sym([(100, 104), (74, 124), (100, 128)], SN, SND)
    sym([(74, 124), (80, 140), (100, 128)], SND, X); sym([(80, 140), (100, 142), (100, 128)], SND, X)

def heart(s, cx, cy, r, c1="#F07A86", c2="#E25C6C"):
    p = lambda x, y: (cx + x * r, cy + y * r)
    s.poly([p(0, -.35), p(-.55, -.85), p(-1, -.45), p(0, 1)], c1); s.poly([p(0, -.35), p(.55, -.85), p(1, -.45), p(0, 1)], c2)
    s.poly([p(-1, -.45), p(-.9, .05), p(0, 1)], c2)


def syringe(s, x, y, k=1.0, ang=-40):
    g = f'<g transform="translate({x} {y}) rotate({ang}) scale({k})">'
    s.raw(g)
    s.poly([(-34, -9), (20, -9), (20, 0), (-34, 0)], "#EEF5FB"); s.poly([(-34, 0), (20, 0), (20, 9), (-34, 9)], "#CFE0EF")
